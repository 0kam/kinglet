"""Generate C assets for the Grove Vision AI V2 bird firmware.

Writes mcu/firmware/bird_pdm/mel_assets.{h,c}:
  - hann window (1024, fp32) and sparse mel filterbank rows (torchaudio
    MelSpectrogram defaults: power 2, htk scale, norm None, f 0..16k, 128 mels)
  - normalization (mel_mu/mel_sd) and TFLite input quantization (scale, zero point)
  - class codes (318 rows, "other" last)
  - golden reference: the host int8-TFLite probabilities for a synthetic window of
    LCG noise that the firmware regenerates (bird_golden_fill in bird_pdm.c), so the
    on-device mel + int8 inference can be checked end to end at boot.

Defaults = the deployed XS model (DISTILL_ROOT/xs_pub_deploy, mcu/export_int8.py). The input
quantization parameters are those of the converted model (printed by export_int8.py --stage
convert); pass them if they change.
  python mcu/gen_mel_assets.py [--write-golden]
"""

import argparse
import sys
from pathlib import Path

import numpy as np
import torch
import torchaudio

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from common.config import DISTILL_ROOT  # noqa: E402
from train.backbones import MEL, SR  # noqa: E402

DEPLOY = DISTILL_ROOT / "xs_pub_deploy"


def c_array(name: str, a: np.ndarray, ctype: str, per_line: int = 12) -> str:
    flat = a.ravel()
    fmt = (lambda v: f"{v:.8e}f") if ctype == "float" else (lambda v: str(int(v)))
    lines = [", ".join(fmt(v) for v in flat[i:i + per_line]) for i in range(0, len(flat), per_line)]
    return f"const {ctype} {name}[{len(flat)}] = {{\n  " + ",\n  ".join(lines) + "\n};\n"


def golden_reference(dst_probs: Path) -> None:
    """Host int8-TFLite outputs for the firmware's LCG golden window (same LCG as bird_golden_fill in bird_pdm.c):
    golden_probs_int8.npy (318 probabilities) and golden_emb_int8.npy (1,280-byte int8 feature) next to dst_probs."""
    from mcu.board_pcm_test import host_models, quantize_input, tflite_run

    x, audio = 1, np.empty(160000, np.int16)
    for i in range(len(audio)):
        x = (1103515245 * x + 12345) & 0x7FFFFFFF
        audio[i] = ((x >> 16) & 0xFFF) - 2048
    _, it, mel = host_models()
    probs, feat = tflite_run(it, quantize_input(it, mel(audio[None])))
    np.save(dst_probs, probs[0])
    np.save(dst_probs.with_name("golden_emb_int8.npy"), feat[0])


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--in-scale", type=float, default=0.023585379123687744)
    ap.add_argument("--in-zp", type=int, default=-33)
    ap.add_argument("--deploy-state", type=Path, default=DEPLOY / "deploy_state.pt")
    ap.add_argument("--golden-probs", type=Path, default=DEPLOY / "golden_probs_int8.npy",
                    help="host int8-TFLite probs for the LCG window (the device runs int8, so "
                         "an fp32 reference fails the check by ordinary quantization error)")
    ap.add_argument("--write-golden", action="store_true",
                    help="first compute --golden-probs (and golden_emb_int8.npy) with the host int8 TFLite model")
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parent / "firmware/bird_pdm")
    args = ap.parse_args()
    OUT = args.out
    if args.write_golden:
        golden_reference(args.golden_probs)

    state = torch.load(args.deploy_state, map_location="cpu", weights_only=False)
    codes = [str(c) for c in state["codes"]]
    n_fft, hop, n_mels = MEL["n_fft"], MEL["hop_length"], MEL["n_mels"]

    window = torch.hann_window(n_fft).numpy().astype(np.float32)
    fb = torchaudio.functional.melscale_fbanks(  # (n_freqs, n_mels), MelSpectrogram defaults
        n_freqs=n_fft // 2 + 1, f_min=0.0, f_max=SR / 2, n_mels=n_mels,
        sample_rate=SR, norm=None, mel_scale="htk").numpy().astype(np.float32).T  # (n_mels, 513)

    starts, weights, lens = [], [], []
    for row in fb:
        nz = np.flatnonzero(row)
        s, e = (nz[0], nz[-1] + 1) if len(nz) else (0, 0)
        starts.append(s)
        lens.append(e - s)
        weights.append(row[s:e])
    offs = np.r_[0, np.cumsum(lens)]

    # golden: deterministic LCG noise regenerated on the device (bird_golden_fill in
    # bird_pdm.c; a stored 5 s window would overflow the 256 KB rodata region). The
    # reference probs are the host int8 TFLite on that window (--golden-probs).
    ref = np.load(args.golden_probs).astype(np.float32)
    assert len(ref) == len(codes), (len(ref), len(codes))

    OUT.mkdir(parents=True, exist_ok=True)
    h = [
        "// Generated by gen_mel_assets.py - do not edit.",
        "#ifndef BIRD_MEL_ASSETS_H_",
        "#define BIRD_MEL_ASSETS_H_",
        "#include <stdint.h>",
        f"#define BIRD_SR {SR}",
        f"#define BIRD_N_FFT {n_fft}",
        f"#define BIRD_HOP {hop}",
        f"#define BIRD_N_MELS {n_mels}",
        f"#define BIRD_N_FRAMES {1 + 160000 // hop}",
        f"#define BIRD_N_CLASSES {len(codes)}",
        f"#define BIRD_MEL_MU {state['mel_mu']:.8e}f",
        f"#define BIRD_MEL_SD {state['mel_sd']:.8e}f",
        f"#define BIRD_IN_SCALE {args.in_scale:.10e}f",
        f"#define BIRD_IN_ZP ({args.in_zp})",
        "extern const float bird_hann[BIRD_N_FFT];",
        "extern const uint16_t bird_mel_start[BIRD_N_MELS];",
        "extern const uint16_t bird_mel_len[BIRD_N_MELS];",
        "extern const uint32_t bird_mel_off[BIRD_N_MELS + 1];",
        f"extern const float bird_mel_w[{int(offs[-1])}];",
        "extern const char *const bird_codes[BIRD_N_CLASSES];",
        "/* golden audio = LCG noise, generate with bird_golden_fill() (see bird_pdm.c) */",
        "extern const float bird_golden_probs[BIRD_N_CLASSES];",
        "#endif",
    ]
    (OUT / "mel_assets.h").write_text("\n".join(h) + "\n")

    c = ["// Generated by gen_mel_assets.py - do not edit.", '#include "mel_assets.h"', ""]
    c.append(c_array("bird_hann", window, "float"))
    c.append(c_array("bird_mel_start", np.array(starts), "uint16_t", 20))
    c.append(c_array("bird_mel_len", np.array(lens), "uint16_t", 20))
    c.append(c_array("bird_mel_off", offs, "uint32_t", 20))
    c.append(c_array("bird_mel_w", np.concatenate(weights), "float"))
    code_lit = ", ".join(f'"{x}"' for x in codes)
    c.append(f"const char *const bird_codes[{len(codes)}] = {{{code_lit}}};\n")
    c.append(c_array("bird_golden_probs", ref, "float"))
    (OUT / "mel_assets.c").write_text("\n".join(c))
    top = np.argsort(ref)[::-1][:5]
    print(f"wrote {OUT}/mel_assets.{{h,c}} ({int(offs[-1])} fbank weights)")
    print("golden top5:", [(codes[i], round(float(ref[i]), 4)) for i in top])


if __name__ == "__main__":
    main()
